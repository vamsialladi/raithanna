export const LanguageContext = createContext({
  language: 'English',
  setLanguage: () => {},
  t: (key) => key,
})

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    return localStorage.getItem('raithanna_lang') || 'English'
  })

  const setLanguage = (lang) => {
    setLanguageState(lang)
    localStorage.setItem('raithanna_lang', lang)
  }

  const t = (key) => {
    const langDict = translations[language] || translations.English
    return langDict[key] ?? translations.English[key] ?? key
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, availableLanguages: Object.keys(translations) }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useTranslation() {
  return useContext(LanguageContext)
}
